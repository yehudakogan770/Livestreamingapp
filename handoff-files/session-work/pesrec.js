const { chromium } = require('playwright-core');
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
  const p = await b.newPage({ viewport: { width: 1600, height: 950 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('http://localhost:1420');
  await p.getByRole('button', { name: 'Skip for now' }).click();
  await p.getByRole('button', { name: 'Add input' }).first().click();
  await p.getByRole('button', { name: '12 Pesukim One word at a time' }).click();
  await p.getByRole('dialog').getByRole('button', { name: 'Add input' }).click();
  await p.waitForTimeout(300);
  console.log('card:', await p.locator('.pk').textContent());
  await p.getByRole('button', { name: 'Type or paste the 12 pesukim' }).click();
  await p.getByRole('button', { name: 'Paste all 12…' }).click();
  await p.getByLabel('Paste the pesukim').fill('Mendel: תּוֹרָה צִוָּה לָנוּ מֹשֶׁה מוֹרָשָׁה קְהִלַּת יַעֲקֹב\nChaya: שְׁמַע יִשְׂרָאֵל ה׳-אֱלֹקֵינוּ ה׳ אֶחָד');
  await p.getByRole('button', { name: 'Use these' }).click();
  await p.getByRole('button', { name: 'Word + pasuk bar' }).click();
  await p.screenshot({ path: 'pes-editor.png' });
  await p.getByRole('button', { name: 'Done' }).click();
  await p.waitForTimeout(200);
  await p.getByRole('button', { name: /^TAKE/ }).click();
  await p.waitForTimeout(1200);
  await p.keyboard.press('Space');
  await p.getByRole('button', { name: 'REC' }).click();
  await p.waitForTimeout(2000);
  await p.locator('.bc-btn').first().click();
  await p.getByRole('button', { name: 'Stop recording' }).click();
  await p.waitForTimeout(1000);
  const url = await p.locator('.bc-saved a').getAttribute('href');
  await p.evaluate(async (url) => {
    const v = document.createElement('video');
    v.muted = true; v.src = url; v.style.cssText = 'position:fixed;left:0;top:0;width:960px;height:540px;z-index:99999;background:#000';
    document.body.appendChild(v);
    await new Promise((r) => (v.onloadeddata = r));
    v.currentTime = 1.2; await new Promise((r) => (v.onseeked = r));
  }, url);
  await p.screenshot({ path: 'pes-rec.png' });
  console.log('errors', errs);
  await b.close();
})();
