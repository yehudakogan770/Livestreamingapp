const { chromium } = require('playwright-core');
(async () => { const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } }); const errs=[]; p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:8765/Main.dc.html'); await p.waitForTimeout(2000);
await p.getByRole('button', { name: /All three/ }).click(); await p.waitForTimeout(400);
const names = () => p.evaluate(() => [...document.querySelectorAll('span')].filter(s => s.style.position==='absolute' && s.style.bottom==='6px').map(s=>s.textContent).join(' / '));
console.log('program names:', await names());
await p.screenshot({ path: 'shots/all.png' });
const over = await p.evaluate(() => { const out=[]; for (const el of document.querySelectorAll('button, span')) { if (el.children.length===0 && el.scrollWidth > el.clientWidth+2 && getComputedStyle(el).textOverflow!=='ellipsis' && el.clientWidth>0) out.push(el.textContent.slice(0,30)); } return out; });
console.log('overflow:', over);
const takes = p.getByRole('button', { name: /^TAKE · / });
console.log('take buttons', await takes.count());
await takes.nth(1).click(); await p.waitForTimeout(1300);
console.log('after Back TAKE:', await names());
await p.getByRole('button', { name: 'Tribute.mp4', exact: true }).first().dblclick(); await p.waitForTimeout(300);
console.log('after dbl-click Tribute on Live:', await names());
await p.getByRole('button', { name: /Back = Live · off/ }).click(); await p.waitForTimeout(300);
console.log('after Back = Live on:', await names());
await p.fill('input[aria-label="Message for the stage"]', 'Two minutes please');
await p.getByRole('button', { name: 'Show on monitor' }).last().click(); await p.waitForTimeout(200);
console.log('monitor shows:', await p.evaluate(() => [...document.querySelectorAll('span')].some(s => s.textContent === 'Two minutes please')));
await p.getByRole('button', { name: /Full controls/ }).first().click(); await p.waitForTimeout(300);
console.log('back to single view (Live selected):', await p.getByRole('button', { name: /Live Screen/ }).first().getAttribute('aria-pressed'));
console.log('errors', errs); await b.close(); })();
