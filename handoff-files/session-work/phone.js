const { chromium, devices } = require('playwright-core');
(async () => {
  const b = await chromium.launch({executablePath:'/opt/pw-browsers/chromium-1194/chrome-linux/chrome'});
  const ctx = await b.newContext({ ...devices['Pixel 7'] });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', (e) => errs.push(e.message));
  p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
  const base = 'http://127.0.0.1:8767';
  await p.goto(base);
  await p.screenshot({ path: 'ph-login.png' });
  await p.fill('#pin', '1111');
  await p.click('text=Connect');
  await p.waitForTimeout(1200);
  console.log('wrong pin msg:', await p.textContent('#login-error'));
  await p.fill('#pin', '4321');
  await p.click('text=Connect');
  await p.waitForSelector('#app:not([hidden])');
  await p.waitForTimeout(500);
  console.log('event:', await p.textContent('#event'), 'next:', await p.textContent('#next-name'));
  await p.screenshot({ path: 'ph-screens.png', fullPage: true });
  // Put Welcome slide in Next and TAKE
  await p.click('[data-source="cam"]');
  await p.waitForTimeout(300);
  console.log('next after tap:', await p.textContent('#next-name'));
  await p.click('#take');
  await p.waitForTimeout(1500);
  console.log('air after take:', await p.textContent('#air-name'));
  await p.selectOption('#preset-pick','p1'); await p.waitForTimeout(400); console.log('next after preset:', await p.textContent('#next-name'), 'tiles:', await p.locator('.tile').count()); await p.screenshot({ path: 'ph-preset.png', fullPage: true });
  await p.click('text=Start countdown');
  await p.waitForTimeout(300);
  await p.click('[data-tab="timer"]');
  await p.waitForTimeout(1300);
  console.log('timer:', await p.textContent('#cd-time'), await p.textContent('#cd-state'));
  await p.click('text=Last 30 s');
  await p.waitForTimeout(400);
  console.log('after last 30:', await p.textContent('#cd-time'));
  await p.screenshot({ path: 'ph-timer.png' });
  await p.click('[data-tab="stage"]');
  await p.click('text=Please wrap up');
  await p.waitForTimeout(400);
  console.log('stage:', await p.textContent('#stage-now'));
  await p.screenshot({ path: 'ph-stage.png' });
  // PANIC via hold
  await p.click('[data-tab="screens"]');
  const box = await p.locator('#panic').boundingBox();
  await p.mouse.move(box.x + 10, box.y + 10); await p.mouse.down(); await p.waitForTimeout(1000); await p.mouse.up();
  await p.waitForTimeout(400);
  console.log('panic banner shown:', await p.isVisible('#panic-banner'));
  await p.screenshot({ path: 'ph-panic.png' });
  const b2 = await p.locator('#panic-off').boundingBox();
  await p.mouse.move(b2.x + 10, b2.y + 10); await p.mouse.down(); await p.waitForTimeout(1000); await p.mouse.up();
  await p.waitForTimeout(400);
  console.log('panic banner after off:', await p.isVisible('#panic-banner'));
  // Tablet view
  const t = await (await b.newContext({ ...devices['iPad Pro 11 landscape'] })).newPage();
  await t.goto(base); await t.fill('#pin', '4321'); await t.click('text=Connect'); await t.waitForTimeout(800);
  await t.screenshot({ path: 'ph-tablet.png' });
  console.log('errors:', errs);
  await b.close();
})();
