const { chromium } = require('playwright-core');
const dir = process.cwd();
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
  const p = await b.newPage({ viewport: { width: 1400, height: 900 } });
  p.setDefaultTimeout(60000);
  await p.addInitScript(() => localStorage.setItem('lumora.textSize', 'normal'));
  const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && !m.text().includes('404') && errs.push(m.text()));
  await p.goto('http://localhost:1420');
  await p.getByRole('button', { name: 'Skip for now' }).click();
  await p.getByRole('button', { name: 'Add input' }).first().click();
  await p.getByRole('button', { name: /^Picture/ }).click();
  const fc = p.waitForEvent('filechooser'); await p.getByRole('button', { name: 'Choose file…' }).click(); await (await fc).setFiles(`${dir}/pic2.png`);
  await p.getByRole('dialog').getByRole('button', { name: 'Add input' }).click();
  await p.waitForTimeout(300);
  await p.locator('.tile').first().locator('button:has-text("⋯")').first().click();
  await p.getByRole('button', { name: /^Adjust picture/ }).click();
  await p.getByRole('button', { name: 'Warm stage' }).click();
  await p.getByRole('slider', { name: 'Exposure' }).fill('0.5');
  await p.waitForTimeout(1500);
  await p.screenshot({ path: 'adj-colour.png' });
  await p.getByRole('tab', { name: 'Crop & position' }).click();
  await p.getByRole('slider', { name: 'Left', exact: true }).fill('20');
  await p.getByRole('slider', { name: 'Rotate' }).fill('10');
  await p.getByRole('tab', { name: 'Effects' }).click();
  await p.getByLabel('Vignette (dark edges) amount').fill('70');
  await p.waitForTimeout(1500);
  await p.screenshot({ path: 'adj-crop.png' });
  console.log('hist bars:', await p.locator('.is__hist i').count());
  console.log('errors', errs);
  await b.close();
})();
