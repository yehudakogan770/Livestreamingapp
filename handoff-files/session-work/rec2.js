const { chromium } = require('playwright-core');
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
  const p = await b.newPage({ viewport: { width: 1600, height: 950 } });
  const errs = [];
  p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('http://localhost:1420');
  await p.getByRole('button', { name: 'Skip for now' }).click();
  await p.getByRole('button', { name: 'Make one and put it in Next' }).click();
  await p.waitForTimeout(300);
  await p.getByRole('button', { name: /^TAKE/ }).click();
  await p.waitForTimeout(1200);
  await p.getByRole('button', { name: 'REC' }).click();
  await p.waitForTimeout(2500);
  await p.locator('.bc-btn').first().click();
  await p.getByRole('button', { name: 'Stop recording' }).click();
  await p.waitForTimeout(1200);
  const url = await p.locator('.bc-saved a').getAttribute('href');
  await p.evaluate(async (url) => {
    const v = document.createElement('video');
    v.muted = true; v.src = url; v.style.cssText = 'position:fixed;left:0;top:0;width:960px;height:540px;z-index:99999;background:#000';
    document.body.appendChild(v);
    await new Promise((r) => (v.onloadeddata = r));
    v.currentTime = 1; await new Promise((r) => (v.onseeked = r));
  }, url);
  await p.screenshot({ path: 'rec-countdown.png' });
  await p.evaluate(() => document.querySelector('video[style*="99999"]').remove());
  // GO LIVE with nowhere to go opens the settings
  await p.getByRole('button', { name: 'GO LIVE' }).click();
  await p.waitForTimeout(300);
  await p.getByRole('button', { name: '+ Add a destination' }).click();
  await p.getByRole('button', { name: '+ Add a destination' }).click();
  await p.screenshot({ path: 'rec-dialog.png' });
  await p.getByLabel('Stream key').first().fill('abcd-efgh');
  await p.getByRole('button', { name: 'Done' }).click();
  await p.getByRole('button', { name: 'GO LIVE' }).click();
  console.log('confirm:', await p.locator('.confirm__text').textContent());
  await p.getByRole('button', { name: 'Go live', exact: true }).click();
  await p.waitForTimeout(600);
  console.log('bar:', await p.locator('footer.bar').first().textContent());
  await p.screenshot({ path: 'rec-golive.png' });
  console.log('errors', errs);
  await b.close();
})();
