const { chromium } = require('playwright');
const S = process.argv[2];
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
  const pg = await b.newPage({ viewport: { width: 1600, height: 900 } });
  await pg.goto('http://localhost:1421/?demo');
  await pg.waitForTimeout(1200);
  await pg.evaluate(() => localStorage.clear());
  for (let i = 0; i < 45; i++) await pg.keyboard.press('ArrowRight');
  await pg.keyboard.press('Control+k');
  for (let i = 0; i < 90; i++) await pg.keyboard.press('ArrowRight');
  await pg.keyboard.press('3');
  await pg.keyboard.press('Control+d');
  for (let i = 0; i < 120; i++) await pg.keyboard.press('ArrowRight');
  await pg.keyboard.press('4');
  await pg.keyboard.press('Home');
  for (let i = 0; i < 20; i++) await pg.keyboard.press('ArrowRight');
  await pg.keyboard.press('Control+t');
  await pg.fill('.insp__words', 'Dana Levi\nHost');
  await pg.locator('.insp__words').blur();
  await pg.click('text=Music & pictures');
  const rows = await pg.evaluate(() => [...document.querySelectorAll('.tl__row')].map((r) => parseFloat(r.style.top)));
  await pg.locator('.media__item:has-text("Music bed")').dragTo(pg.locator('.tl__scroll'), { targetPosition: { x: 2, y: rows[rows.length - 1] + 10 } });
  await pg.click('.clip--video:has-text("Wide") >> nth=0');
  await pg.click('.pp .tabs button:nth-child(2)');
  await pg.click('text=Basic correction');
  await pg.click('.ed__status');
  for (let i = 0; i < 45; i++) await pg.keyboard.press('ArrowRight');
  await pg.waitForTimeout(800);
  await pg.screenshot({ path: S + '/site-edit.png' });
  await b.close();
})();
