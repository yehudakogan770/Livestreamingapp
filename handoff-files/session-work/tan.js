const { chromium } = require('playwright-core');
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
  const p = await b.newPage({ viewport: { width: 1600, height: 900 } });
  p.setDefaultTimeout(15000);
  const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('response', (r) => r.status() >= 400 && errs.push(r.status() + ' ' + r.url()));
  await p.addInitScript(() => localStorage.setItem('lumora.textSize', 'normal'));
  await p.goto('http://localhost:1420');
  await p.getByRole('button', { name: 'Skip for now' }).click();
  await p.getByRole('button', { name: 'Add input' }).first().click();
  await p.getByRole('button', { name: /^Tanach & Tehillim/ }).click();
  await p.getByRole('dialog').getByRole('button', { name: 'Add input' }).click();
  await p.locator('.tile__pick').nth(0).dblclick();
  await p.getByRole('button', { name: /Options for / }).first().click();
  await p.getByRole('button', { name: 'Choose the passage…' }).click();
  await p.waitForTimeout(1200);
  await p.screenshot({ path: 'tan1.png' });
  await p.getByRole('button', { name: 'Next verse ▶' }).click();
  await p.getByRole('button', { name: 'Next verse ▶' }).click();
  await p.getByRole('button', { name: 'Along the bottom' }).click();
  await p.waitForTimeout(500);
  await p.screenshot({ path: 'tan2.png' });
  await p.getByLabel('Find words').fill('shepherd');
  await p.getByRole('button', { name: 'Find', exact: true }).click();
  await p.waitForTimeout(8000);
  await p.screenshot({ path: 'tan3.png' });
  await p.getByRole('button', { name: 'Full screen' }).click();
  await p.getByRole('button', { name: 'A verse at a time' }).click();
  await p.getByLabel('Book').selectOption('0');
  await p.waitForTimeout(1500);
  await p.keyboard.press('Escape');
  await p.waitForTimeout(500);
  await p.screenshot({ path: 'tan4.png' });
  console.log('errors', errs);
  await b.close();
})();
