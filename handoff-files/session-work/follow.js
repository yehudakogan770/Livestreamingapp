const { chromium } = require('playwright-core');
(async () => { const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } }); const errs=[]; p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:8765/Main.dc.html'); await p.waitForTimeout(2000);
const pgName = () => p.evaluate(() => { const s=[...document.querySelectorAll('span')].find(x=>x.textContent==='Program' && x.nextElementSibling); return s.nextElementSibling.textContent; });
const tabs = () => p.evaluate(() => [...document.querySelectorAll('button[aria-pressed]')].slice(0,3).map(b=>b.innerText.replace(/\s+/g,' ').slice(0,40)).join(' | '));
await p.getByRole('button', { name: /Back = Live/ }).click(); await p.waitForTimeout(200);
console.log('tabs:', await tabs());
await p.getByRole('button', { name: /Back Screen/ }).first().click(); await p.waitForTimeout(200);
console.log('Back program while following:', await pgName());
await p.getByRole('button', { name: /Live Screen/ }).first().click(); await p.waitForTimeout(200);
await p.getByRole('button', { name: 'CUT', exact: true }).click(); await p.waitForTimeout(200);
const live = await pgName();
await p.getByRole('button', { name: /Back Screen/ }).first().click(); await p.waitForTimeout(200);
console.log('after Live CUT -> live', live, '| back', await pgName());
await p.screenshot({ path: 'shots/follow.png', clip: { x: 0, y: 34, width: 1440, height: 130 } });
await p.getByRole('button', { name: 'CUT', exact: true }).click(); await p.waitForTimeout(200);
console.log('after CUT on Back -> follow button:', await p.getByRole('button', { name: /Back = Live/ }).getAttribute('aria-pressed'));
console.log('errors', errs); await b.close(); })();
