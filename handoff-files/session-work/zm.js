const { chromium } = require('playwright-core');
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
  const ctx = await b.newContext({ viewport: { width: 1600, height: 900 }, timezoneId: 'America/New_York' });
  const p = await ctx.newPage();
  p.setDefaultTimeout(15000);
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  p.on('dialog', (d) => d.accept());
  await p.clock.install({ time: new Date('2026-09-25T18:14:00-04:00') });
  await p.addInitScript(() => localStorage.setItem('lumora.textSize', 'normal'));
  await p.goto('http://localhost:1420');
  await p.getByRole('button', { name: 'Skip for now' }).click();
  await p.getByRole('button', { name: 'Event', exact: true }).click();
  await p.getByText('Zmanim and Shabbos…').click();
  await p.getByLabel('City').selectOption('New York');
  await p.getByText('End the live stream and recording by').click();
  await p.screenshot({ path: 'zm0.png' });
  await p.getByRole('button', { name: 'Save' }).click();
  await p.getByRole('button', { name: 'Add input' }).first().click();
  await p.getByRole('button', { name: /^Hebrew date & zmanim/ }).click();
  await p.getByRole('dialog').getByRole('button', { name: 'Add input' }).click();
  await p.locator('.tile__pick').nth(0).dblclick();
  await p.clock.runFor(1500);
  await p.screenshot({ path: 'zm1.png' });
  await p.getByRole('button', { name: /Options for / }).first().click();
  await p.getByRole('button', { name: 'Look, city and Shabbos…' }).click();
  await p.getByRole('button', { name: 'Countdown to candle lighting' }).click();
  await p.getByRole('button', { name: 'Cancel' }).click();
  await p.clock.runFor(1500);
  await p.screenshot({ path: 'zm2.png' });
  await p.getByRole('button', { name: /^REC/ }).click();
  await p.clock.runFor(2000);
  await p.locator('.selector__name', { hasText: 'Monitor' }).click();
  await p.clock.runFor(1500);
  await p.screenshot({ path: 'zm5.png' });
  console.log('errors', errs);
  await b.close();
})();
